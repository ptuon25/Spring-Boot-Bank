package com.tuon.tbank.entity.person;

import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonIgnore;
import com.tuon.tbank.entity.audit.AuditRecord;
import com.tuon.tbank.entity.transaction.reversalTransaction.TransactionReversal;
import jakarta.persistence.*;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.proxy.HibernateProxy;

import java.time.LocalDate;
import java.util.HashSet;
import java.util.Objects;
import java.util.Set;

/**
 * Represents a person in the system, which can be either a client or an employee.
 *
 * <p>This is the abstract base of the person hierarchy. It holds the data shared
 * by every kind of person, such as identification, credentials, and the audit and
 * reversal records in which the person takes part.</p>
 *
 * <p>The hierarchy uses {@link InheritanceType#JOINED}: the common data is stored
 * in the {@code person} table, and the data specific to each subclass
 * ({@link Client}, {@link Employee}) is stored in its own table, linked by the
 * primary key.</p>
 */
@Entity
@Getter
@Setter
@Table(name = "person")
@Inheritance(strategy = InheritanceType.JOINED)
public abstract class Person {

    /**
     * Stores the unique identifier of the person.
     *
     * <p>The value is generated by the database
     * ({@code GenerationType.IDENTITY}), and no setter is generated for this
     * field.</p>
     */
    @Setter(AccessLevel.NONE)
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Stores the person's full name.
     */
    private String name;

    /**
     * Stores the person's date of birth.
     *
     * <p>Its JSON representation uses the {@code yyyy-MM-dd} date format.</p>
     */
    @JsonFormat(shape = JsonFormat.Shape.STRING, pattern = "yyyy-MM-dd")
    private LocalDate birthDate;

    /**
     * Stores the person's identification document.
     *
     * <p>Uniqueness is not enforced by a database constraint on this field. For
     * clients, it is checked by the service layer, which also normalizes the
     * value before persisting it.</p>
     */
    private String document;

    /**
     * Stores the person's e-mail address, which is also used as the login
     * identifier.
     *
     * <p>The column is mandatory and unique, so the database rejects duplicates
     * even among logically deleted records.</p>
     */
    @Column(nullable = false, unique = true)
    private String email;

    /**
     * Stores the encoded (hashed) password of the person.
     *
     * <p>The plain-text password is never persisted. This field is annotated with
     * {@code @JsonIgnore}, so it is neither serialized into responses nor read
     * from request bodies.</p>
     *
     * <p>The generated setter is {@code protected}, so it is available only to
     * this class and its subclasses (for example, in constructors). Code outside
     * the hierarchy must change the password through
     * {@link #changePasswordHash(String)}.</p>
     */
    @Setter(AccessLevel.PROTECTED)
    @JsonIgnore
    private String passwordHash;

    /**
     * Stores the transaction reversal requests made by this person.
     *
     * <p>This is the inverse side of the relationship, mapped by the
     * {@code requestedBy} field in {@link TransactionReversal}. Persist
     * operations are not cascaded (only {@code DETACH} is), and
     * {@code orphanRemoval} is enabled.</p>
     *
     * <p>No setter is generated for this field. Changes to the relationship
     * must be made through the owning side.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "requestedBy", cascade = CascadeType.DETACH, orphanRemoval = true)
    private Set<TransactionReversal> transactionReversals = new HashSet<>();

    /**
     * Stores the audit records of actions performed by this person.
     *
     * <p>This is the inverse side of the relationship, mapped by the
     * {@code performedBy} field in {@link AuditRecord}. The field is not
     * serialized to JSON.</p>
     *
     * <p>No setter is generated for this field. Changes to the relationship
     * must be made through the owning side.</p>
     */
    @Setter(AccessLevel.NONE)
    @JsonIgnore
    @OneToMany(mappedBy = "performedBy")
    private Set<AuditRecord> auditRecordsPerformedBy = new HashSet<>();

    /**
     * Stores the audit records in which this person is the subject of the action.
     *
     * <p>This is the inverse side of the relationship, mapped by the
     * {@code person} field in {@link AuditRecord}. It differs from
     * {@link #auditRecordsPerformedBy}, which holds the records of actions
     * performed <b>by</b> this person. The field is not serialized to JSON.</p>
     *
     * <p>No setter is generated for this field. Changes to the relationship
     * must be made through the owning side.</p>
     */
    @Setter(AccessLevel.NONE)
    @JsonIgnore
    @OneToMany(mappedBy = "person")
    private Set<AuditRecord> auditRecordsPerson = new HashSet<>();

    /**
     * Indicates whether the person has been logically deleted.
     *
     * <p>The default value is {@code false}. Deletion does not remove the row, so
     * the financial and audit history is preserved. Records marked as deleted are
     * hidden only by queries that explicitly filter this flag, such as the
     * {@code ...AndDeletedFalse} methods of the client repository.</p>
     */
    private boolean deleted = false;

    /**
     * Creates an empty person instance.
     *
     * <p>This constructor is required by JPA for entity instantiation.</p>
     */
    public Person() {
    }

    /**
     * Creates a person with the specified identification and credentials.
     *
     * @param id           the person's identifier
     * @param name         the person's full name
     * @param birthDate    the person's date of birth
     * @param document     the person's identification document
     * @param email        the person's e-mail address
     * @param passwordHash the person's encoded password
     */
    public Person(Long id, String name, LocalDate birthDate, String document, String email, String passwordHash) {
        this.id = id;
        this.name = name;
        this.birthDate = birthDate;
        this.document = document;
        this.email = email;
        this.passwordHash = passwordHash;
    }

    /**
     * Replaces the stored password hash.
     *
     * <p>The value must already be encoded: this method does not hash anything.
     * Validating the plain-text password and encoding it with a
     * {@code PasswordEncoder} is the caller's responsibility.</p>
     *
     * @param newPasswordHash the new encoded password
     * @throws IllegalArgumentException if the hash is {@code null} or blank
     */
    public void changePasswordHash(String newPasswordHash) {
        if (newPasswordHash == null || newPasswordHash.isBlank()) {
            throw new IllegalArgumentException("Password hash cannot be null or blank");
        }
        this.passwordHash = newPasswordHash;
    }

    /**
     * Compares this person with another object by identity.
     *
     * <p>Two persons are equal when they have the same effective class (Hibernate
     * proxies are unwrapped to their real class) and the same non-null
     * identifier. A person that has not been persisted yet is equal only to
     * itself.</p>
     *
     * @param o the object to compare with
     * @return {@code true} if both represent the same persisted person
     */
    @Override
    public final boolean equals(Object o) {
        if (this == o) return true;
        if (o == null) return false;

        Class<?> oEffectiveClass = o instanceof HibernateProxy
                ? o.getClass().getSuperclass()
                : o.getClass();

        Class<?> thisEffectiveClass = this instanceof HibernateProxy
                ? this.getClass().getSuperclass()
                : this.getClass();

        if (thisEffectiveClass != oEffectiveClass) return false;

        Person person = (Person) o;

        return getId() != null && Objects.equals(getId(), person.getId());
    }

    /**
     * Returns a hash code based on the effective class of the person.
     *
     * <p>The value does not depend on the identifier, so it stays the same
     * before and after the entity is persisted. This keeps the person valid
     * inside hash-based collections.</p>
     *
     * @return the hash code of the effective class
     */
    @Override
    public final int hashCode() {
        return this instanceof HibernateProxy
                ? this.getClass().getSuperclass().hashCode()
                : getClass().hashCode();
    }
}
