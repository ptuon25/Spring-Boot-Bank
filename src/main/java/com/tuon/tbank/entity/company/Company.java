package com.tuon.tbank.entity.company;

import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonIgnore;
import com.tuon.tbank.entity.account.BusinessAccount;
import com.tuon.tbank.entity.audit.AuditRecord;
import com.tuon.tbank.entity.person.Client;
import com.tuon.tbank.entity.person.Person;
import com.tuon.tbank.enums.company.CompanyStatus;
import jakarta.persistence.*;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.proxy.HibernateProxy;

import java.time.LocalDate;
import java.util.HashSet;
import java.util.Objects;
import java.util.Set;

/**
 * Represents a business (legal entity) registered as a client of the bank.
 *
 * <p>It allows the bank to maintain registration data and identify the
 * companies that use its financial services.</p>
 *
 * <p>This entity serves to represent the company as an institutional client of the bank,
 * keeping its data separate from the data of individual clients {@link Client}.</p>
 */
@Entity
@Table(name = "companies")
@Getter
@Setter
public class Company {

    /**
     * Stores the unique identifier of the company.
     *
     * <p>The value is generated by the database
     * ({@code GenerationType.IDENTITY}), and no setter is generated for this
     * field.</p>
     */
    @Setter(AccessLevel.NONE)
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Stores the company's legal name.
     */

    private String legalName;

    /**
     * Stores the company's trade name.
     */
    private String tradeName;

    /**
     * The principal partner of the company.
     *
     * <p>The partner may be a client or an employee, and multiple companies can have the same partner.</p>
     */
    @ManyToOne
    @JoinColumn(name = "partner_id", nullable = false)
    private Person partner;

    /**
     * Stores the company's registration number, which is a unique identifier for the company.
     */
    private String registrationNumber;

    /**
     * Stores the date on which the company was founded.
     *
     * <p>This date is used to determine the company's age and to track its history.</p>
     * <p>Its JSON representation uses the {@code yyyy-MM-dd} date format.</p>
     */
    @JsonFormat(shape = JsonFormat.Shape.STRING, pattern = "yyyy-MM-dd")
    private LocalDate foundationDate;

    /**
     * Stores the date on which the company was affiliated.
     *
     * <p>This date is used to determine the company's affiliation status and to track its history.</p>
     * <p>Its JSON representation uses the {@code yyyy-MM-dd} date format.</p>
     */
    @JsonFormat(shape = JsonFormat.Shape.STRING, pattern = "yyyy-MM-dd")
    private LocalDate affiliationDate;

    /**
     * Represents the company's status in the bank system.
     *
     * <p>The available values are defined by {@link CompanyStatus}.</p>
     */
    @Enumerated(EnumType.STRING)
    private CompanyStatus status;

    /**
     * Stores the business accounts associated with this company.
     *
     * <p>This is the inverse side of the relationship, mapped by the
     * {@code owner} field in {@link BusinessAccount}.</p>
     *
     * <p>No setter is generated for this field. Changes to the relationship
     * must be made through the owning side, since the inverse side is not
     * persisted.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "owner")
    private Set<BusinessAccount> businessAccounts = new HashSet<>();


    /**
     * Stores the audit records associated with this company.
     *
     * <p>This is the inverse side of the relationship, mapped by the
     * {@code company} field in {@link AuditRecord}.</p>
     *
     * <p>No setter is generated for this field. Changes to the relationship
     * must be made through the owning side, since the inverse side is not
     * persisted.</p>
     */
    @Setter(AccessLevel.NONE)
    @JsonIgnore
    @OneToMany(mappedBy = "company")
    private Set<AuditRecord> auditRecords = new HashSet<>();

    /**
     * Indicates whether the company is marked as deleted.
     *
     * <p>This field is used to implement soft deletion, allowing for the verification of records regardless of their deletion status.</p>
     *
     * <p>Its default value is {@code false}, indicating that the company is not deleted.</p>
     */
    private boolean deleted = false;

    /**
     * Constructs a new {@code Company} instance with default values.
     *
     * <p>This constructor is required by JPA for entity instantiation.</p>
     */
    public Company() {

    }

    /**
     * Constructs a new {@code Company} instance with the specified values.
     *
     * @param id                 the company's unique identifier
     * @param legalName          the company's legal name
     * @param tradeName          the company's trade name
     * @param partner            the person who is the partner of the company
     * @param registrationNumber the company's registration number
     * @param foundationDate     the date on which the company was founded
     * @param affiliationDate    the date on which the company was affiliated
     * @param status             the company's status in the bank system
     */
    public Company(Long id, String legalName, String tradeName, Person partner, String registrationNumber, LocalDate foundationDate, LocalDate affiliationDate, CompanyStatus status) {
        this.id = id;
        this.legalName = legalName;
        this.tradeName = tradeName;
        this.partner = partner;
        this.registrationNumber = registrationNumber;
        this.foundationDate = foundationDate;
        this.affiliationDate = affiliationDate;
        this.status = status;
    }

    /**
     * Compares this company to the specified object for equality.
     *
     * @param o the reference object with which to compare.
     * @return {@code true} if this company is the same as the specified object; {@code false} otherwise.
     */
    @Override
    public final boolean equals(Object o) {
        if (this == o) return true;
        if (o == null) return false;
        Class<?> oEffectiveClass = o instanceof HibernateProxy ? ((HibernateProxy) o).getHibernateLazyInitializer().getPersistentClass() : o.getClass();
        Class<?> thisEffectiveClass = this instanceof HibernateProxy ? ((HibernateProxy) this).getHibernateLazyInitializer().getPersistentClass() : this.getClass();
        if (thisEffectiveClass != oEffectiveClass) return false;
        Company company = (Company) o;
        return getId() != null && Objects.equals(getId(), company.getId());
    }

    /**
     * Returns a hash code value for the company.
     *
     * @return a hash code value for this company.
     * @implSpec The hash code is based on the class of the company, ensuring that
     * instances of the same class have the same hash code.
     */
    @Override
    public final int hashCode() {
        return this instanceof HibernateProxy ? ((HibernateProxy) this).getHibernateLazyInitializer().getPersistentClass().hashCode() : getClass().hashCode();
    }
}
