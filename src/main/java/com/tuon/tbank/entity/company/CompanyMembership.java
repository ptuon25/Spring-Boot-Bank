package com.tuon.tbank.entity.company;

import com.tuon.tbank.entity.person.Client;
import com.tuon.tbank.enums.company.CompanyMemberRole;
import com.tuon.tbank.enums.company.MembershipStatus;
import jakarta.persistence.*;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.Setter;

import java.util.Objects;

/**
 * Represents an additional client association with a company.
 *
 * <p>The company's principal partner is stored in {@link Company#getPartner()}.
 * This entity grants access to other client members through their assigned roles.</p>
 */
@Getter
@Setter
@Entity
@Table(
        name = "company_memberships",
        uniqueConstraints = @UniqueConstraint(
                columnNames = {"company_id", "client_id"}
        )
)
public class CompanyMembership {

    /**
     * Stores the unique identifier of the membership.
     *
     * <p>The value is generated by the database
     * ({@code GenerationType.IDENTITY}), and no setter is generated for this
     * field.</p>
     */
    @Setter(AccessLevel.NONE)
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * The company to which the client belongs.
     */
    @ManyToOne(optional = false)
    @JoinColumn(name = "company_id", nullable = false)
    private Company company;

    /**
     * The client who is a member of the company.
     */
    @ManyToOne(optional = false)
    @JoinColumn(name = "client_id", nullable = false)
    private Client client;

    /**
     * The role of the client within the company.
     */
    @Enumerated(EnumType.STRING)
    private CompanyMemberRole role;

    /**
     * The status of the membership.
     */
    @Enumerated(EnumType.STRING)
    private MembershipStatus status;

    /**
     * Default constructor for JPA.
     */
    public CompanyMembership() {
    }

    /**
     * Constructs a new {@code CompanyMembership} with the specified company, client, role, and status.
     *
     * @param company the company to which the client belongs
     * @param client  the client who is a member of the company
     * @param role    the role of the client within the company
     * @param status  the status of the membership
     */
    public CompanyMembership(Company company, Client client, CompanyMemberRole role, MembershipStatus status) {
        this.company = company;
        this.client = client;
        this.role = role;
        this.status = status;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null || getClass() != o.getClass()) return false;
        CompanyMembership that = (CompanyMembership) o;
        return Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return Objects.hashCode(id);
    }
}