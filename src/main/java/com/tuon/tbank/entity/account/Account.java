package com.tuon.tbank.entity.account;

import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonIgnore;
import com.tuon.tbank.entity.audit.AuditRecord;
import com.tuon.tbank.entity.investment.InvestmentApplication;
import com.tuon.tbank.entity.investment.InvestmentPortfolio;
import com.tuon.tbank.entity.investment.InvestmentRedemption;
import com.tuon.tbank.entity.investment.InvestmentTransaction;
import com.tuon.tbank.entity.transaction.Deposit;
import com.tuon.tbank.entity.transaction.Payment;
import com.tuon.tbank.entity.transaction.Transfer;
import com.tuon.tbank.entity.transaction.Withdrawal;
import com.tuon.tbank.entity.transaction.endpoint.TransferEndpoint;
import com.tuon.tbank.entity.transaction.scheduledTransaction.ScheduledTransaction;
import com.tuon.tbank.enums.account.AccountStatus;
import jakarta.persistence.*;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.proxy.HibernateProxy;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.HashSet;
import java.util.Objects;
import java.util.Set;

/**
 * Represents a bank account with common attributes and relationships.
 * This is an abstract class that serves as a base for specific account types.
 * <p>This class provides a foundation for creating different types of bank accounts, such as checking accounts, savings accounts, etc.</p>
 */
@Entity
@Getter
@Setter
@Inheritance(strategy = InheritanceType.JOINED)
@Table(name = "accounts")
public abstract class Account implements TransferEndpoint {

    /**
     * Stores the unique identifier of the account.
     *
     * <p>The value is generated by the database
     * ({@code GenerationType.IDENTITY}), and no setter is generated for this
     * field.</p>
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Setter(AccessLevel.NONE)
    private Long id;

    /**
     * Stores the account number.
     *
     * <p>The account number is a unique identifier for each account and is used to distinguish one account from another.</p>
     */
    @Column(unique = true, nullable = false)
    private String accountNumber;

    /**
     * Stores the account balance.
     *
     * <p>The balance is represented as a {@link BigDecimal} to ensure precision in financial calculations.</p>
     */
    @Setter(AccessLevel.NONE)
    private BigDecimal balance;

    /**
     * Stores the account opening date.
     *
     * <p>Its JSON representation uses the {@code yyyy-MM-dd} date format.</p>
     */
    @JsonFormat(shape = JsonFormat.Shape.STRING, pattern = "yyyy-MM-dd")
    private LocalDate openingDate;

    /**
     * Stores the account status.
     *
     * <p>The status is represented as an enumerated type {@link AccountStatus}.</p>
     */
    @Enumerated(EnumType.STRING)
    private AccountStatus status;

    /**
     * Stores the deposits associated with the account.
     * <p>Each deposit is linked to a specific account via the {@code destinationAccount} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "destinationAccount")
    private Set<Deposit> deposits = new HashSet<>();

    /**
     * Stores the withdrawals associated with the account.
     * <p>Each withdrawal is linked to a specific account via the {@code sourceAccount} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "sourceAccount")
    private Set<Withdrawal> withdrawals = new HashSet<>();

    /**
     * Stores the payments associated with the account.
     * <p>Each payment is linked to a specific account via the {@code sourceAccount} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "sourceAccount")
    private Set<Payment> payments = new HashSet<>();

    /**
     * Stores the transfers associated with the account.
     * <p>Each transfer is linked to a specific account via the {@code sourceAccount} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "sourceAccount")
    private Set<Transfer> sourceTransfers = new HashSet<>();

    /**
     * Stores the transfers associated with the account.
     * <p>Each transfer is linked to a specific account via the {@code destinationAccount} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "destinationAccount")
    private Set<Transfer> destinationTransfers = new HashSet<>();

    /**
     * Stores the scheduled transactions associated with the account.
     * <p>Each scheduled transaction is linked to a specific account via the {@code sourceAccount} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "sourceAccount")
    private Set<ScheduledTransaction> sourceScheduledTransactions = new HashSet<>();

    /**
     * Stores the scheduled transactions associated with the account.
     * <p>Each scheduled transaction is linked to a specific account via the {@code destinationAccount} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "destinationAccount")
    private Set<ScheduledTransaction> destinationScheduledTransactions = new HashSet<>();

    /**
     * Stores the investment portfolios associated with the account.
     * <p>Each investment portfolio is linked to a specific account via the {@code account} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "account")
    private Set<InvestmentPortfolio> investmentPortfolios = new HashSet<>();

    /**
     * Stores the investment applications associated with the account.
     * <p>Each investment application is linked to a specific account via the {@code sourceAccount} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "sourceAccount")
    private Set<InvestmentApplication> investmentApplications = new HashSet<>();

    /**
     * Stores the investment redemptions associated with the account.
     * <p>Each investment redemption is linked to a specific account via the {@code sourceAccount} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "sourceAccount")
    private Set<InvestmentRedemption> investmentRedemptions = new HashSet<>();

    /**
     * Stores the investment transactions associated with the account.
     * <p>Each investment transaction is linked to a specific account via the {@code destinationAccount} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "destinationAccount")
    private Set<InvestmentTransaction> investmentTransactions = new HashSet<>();

    /**
     * Stores the audit records associated with the account.
     * <p>Each audit record is linked to a specific account via the {@code account} field.</p>
     */
    @Setter(AccessLevel.NONE)
    @JsonIgnore
    @OneToMany(mappedBy = "account")
    private Set<AuditRecord> auditRecords = new HashSet<>();

    /**
     * Indicates whether the account is deleted.
     */
    private boolean deleted = false;

    /**
     * Default constructor for the Account class.
     * <p>This constructor is required by JPA and should not be used directly.</p>
     */
    public Account(){
        this.balance = BigDecimal.ZERO;
        this.openingDate = LocalDate.now();
    }

    /**
     * Constructs an Account with the specified attributes.
     *
     * @param id            the unique identifier of the account
     * @param accountNumber the account number
     * @param balance       the account balance
     * @param openingDate   the account opening date
     * @param status        the account status
     */
    public Account(Long id, String accountNumber, BigDecimal balance, LocalDate openingDate, AccountStatus status) {
        this.id = id;
        this.accountNumber = accountNumber;
        this.balance = balance == null ? BigDecimal.ZERO : balance;
        this.openingDate = openingDate == null ? LocalDate.now() : openingDate;
        this.status = status;
    }

    /**
     * Credits the account with the specified amount.
     *
     * @param amount the amount to credit
     */
    public void credit (BigDecimal amount){
        this.balance = this.balance.add(amount);
    }

    /**
     * Debits the account with the specified amount.
     *
     * @param amount the amount to debit
     */
    public void debit (BigDecimal amount){
        this.balance = this.balance.subtract(amount);
    }

    /**
     * Overrides the equals method to compare Account objects based on their unique identifier (id).
     *
     * @param o the object to compare with
     * @return true if the objects are equal, false otherwise
     */
    @Override
    public final boolean equals(Object o) {
        if (this == o) return true;
        if (o == null) return false;

        Class<?> oEffectiveClass = o instanceof HibernateProxy
                ? o.getClass().getSuperclass()
                : o.getClass();

        Class<?> thisEffectiveClass = this instanceof HibernateProxy
                ? this.getClass().getSuperclass()
                : this.getClass();

        if (thisEffectiveClass != oEffectiveClass) return false;

        Account account = (Account) o;

        return getId() != null && Objects.equals(getId(), account.getId());
    }

    /**
     * Overrides the hashCode method to generate a hash code based on the account's unique identifier (id).
     *
     * @return the hash code of the account
     */
    @Override
    public final int hashCode() {
        return this instanceof HibernateProxy
                ? this.getClass().getSuperclass().hashCode()
                : getClass().hashCode();
    }
}
