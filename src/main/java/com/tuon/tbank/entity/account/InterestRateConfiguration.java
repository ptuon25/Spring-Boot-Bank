package com.tuon.tbank.entity.account;

import com.tuon.tbank.service.account.InterestRateService;
import jakarta.persistence.*;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.Objects;

/**
 * Represents the configuration for interest rates in the banking system.
 * This entity is used to store and manage different interest rate configurations that can be applied to various account types.
 */
@Entity
@Table(name = "interest_rate_configurations", uniqueConstraints = @UniqueConstraint(name = "uk_interest_rate_effective_date", columnNames = "effective_date"))
@Getter
@Setter
public class InterestRateConfiguration {

    /**
     * The unique identifier for the interest rate configuration.
     * This value is generated by the database and is used to uniquely identify each configuration.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Setter(AccessLevel.NONE)
    private Long id;

    /**
     * The interest rate value for this configuration.
     * This is the annual percentage rate (APR) that can be applied to accounts.
     */
    @Column(nullable = false)
    private BigDecimal interestRate;

    /**
     * The effective date from which this interest rate configuration is applicable.
     * This allows for managing different interest rates over time.
     */
    @Column(name = "effective_date", nullable = false)
    private LocalDate effectiveDate;

    /**
     * The date and time when this interest rate configuration was created.
     * This is automatically set by the {@link InterestRateService}.
     */
    @Column(nullable = false)
    private LocalDateTime createdAt;

    /**
     * The date and time when this interest rate configuration was last updated.
     * This is automatically set by the system whenever the configuration is modified.
     */
    public InterestRateConfiguration() {
    }

    /**
     * Constructs a new InterestRateConfiguration with the specified details.
     *
     * @param id            the unique identifier of the configuration
     * @param interestRate  the interest rate value for this configuration
     * @param effectiveDate the effective date from which this configuration is applicable
     * @param createdAt     the date and time when this configuration was created
     */
    public InterestRateConfiguration(Long id, BigDecimal interestRate, LocalDate effectiveDate, LocalDateTime createdAt) {
        this.id = id;
        this.interestRate = interestRate;
        this.effectiveDate = effectiveDate;
        this.createdAt = createdAt;
    }

    /**
     * Overrides the default equals method to compare InterestRateConfiguration objects based on their unique identifier.
     *
     * @param o the object to compare with
     * @return true if the objects are equal, false otherwise
     */
    @Override
    public boolean equals(Object o) {
        if (o == null || getClass() != o.getClass()) return false;
        InterestRateConfiguration that = (InterestRateConfiguration) o;
        return Objects.equals(id, that.id);
    }

    /**
     * Overrides the default hashCode method to generate a hash code based on the unique identifier.
     *
     * @return the hash code of the object
     */
    @Override
    public int hashCode() {
        return Objects.hashCode(id);
    }
}
